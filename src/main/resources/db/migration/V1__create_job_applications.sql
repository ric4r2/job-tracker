create table job_applications (
    id                bigint generated by default as identity primary key,
    version           bigint                   not null default 0,
    company           varchar(200)             not null,
    role              varchar(200)             not null,
    location          varchar(200),
    job_url           varchar(2000),
    source            varchar(100),
    notes             varchar(4000),
    status            varchar(20)              not null,
    applied_on        date,
    next_follow_up_on date,
    created_at        timestamp with time zone not null,
    updated_at        timestamp with time zone not null
);

create index idx_job_applications_status on job_applications (status);
create index idx_job_applications_follow_up on job_applications (next_follow_up_on);

create table status_changes (
    id                 bigint generated by default as identity primary key,
    job_application_id bigint                   not null references job_applications (id) on delete cascade,
    from_status        varchar(20),
    to_status          varchar(20)              not null,
    note               varchar(1000),
    changed_at         timestamp with time zone not null
);

create index idx_status_changes_application on status_changes (job_application_id);
